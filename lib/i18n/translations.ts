const ARABIC_TEXT_PATTERN = /[\u0600-\u06FF]/
const REPLACEMENT_ENTRIES = Object.entries({ ...GENERATED_UI_TRANSLATIONS, ...REVIEWED_TRANSLATIONS })
  .filter(([source]) => source.length > 1 && ARABIC_TEXT_PATTERN.test(source))
  .sort((first, second) => second[0].length - first[0].length)

function preserveReplacementSpacing(source: string, target: string) {
  const leading = source.match(/^\s*/)?.[0] ?? ""
  const trailing = source.match(/\s*$/)?.[0] ?? ""
  return `${leading}${target.trim()}${trailing}`
}

function polishTranslation(value: string) {
  return value
    .replace(/\bWordPress\b|\bWord\b/g, "Wirdy")
    .replace(/\bKoran\b|Qur’an|Qur'an/g, "Quran")
    .replace(/\breader\b/gi, (word) => word[0] === "R" ? "Reciter" : "reciter")
    .replace(/\bParty\b/g, "Hizb")
    .replace(/\bPart (?=\d)/g, "Juz ")
    .replace(/\bverse (?=\d)/gi, "Ayah ")
    .replace(/\bp (?=\d)/g, "p. ")
    .replace(/(\d+) One day\b/g, "$1 days")
    .replace(/(\d+) Page\b/g, (match, count: string) => `${count} ${count === "1" ? "page" : "pages"}`)
    .replace(/\bseal\b|\bstamp\b/gi, "Khatmah")
    .replace(/،/g, ",")
    .replace(/\s+([,.;:!?])/g, "$1")
}

export function translateInterfaceText(value: string) {
  if (!ARABIC_TEXT_PATTERN.test(value)) return value
  const leading = value.match(/^\s*/)?.[0] ?? ""
  const trailing = value.match(/\s*$/)?.[0] ?? ""
  const core = value.slice(leading.length, value.length - trailing.length || undefined)
  const exact = REVIEWED_TRANSLATIONS[core] ?? GENERATED_UI_TRANSLATIONS[core]
  if (exact) return `${leading}${polishTranslation(exact)}${trailing}`

  let translated = replaceArabicSurahNames(core)
  for (const [source, target] of REPLACEMENT_ENTRIES) {
    if (translated.includes(source)) translated = translated.replaceAll(source, preserveReplacementSpacing(source, target))
  }
  return `${leading}${polishTranslation(translated)}${trailing}`
}
